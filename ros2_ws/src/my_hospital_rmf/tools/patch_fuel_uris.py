"""
Step 2: Replace model://X URIs generated by building_map_generator
with full Fuel URIs derived from building.yaml model_name entries.
"""
import yaml
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
building_path = REPO / "ros2_ws/src/my_hospital_rmf/maps/hospital.building.yaml"
world_path    = REPO / "ros2_ws/src/my_hospital_rmf/maps/hospital.world"

with open(building_path) as f:
    bld = yaml.safe_load(f)

fuel_map = {}
for level in bld.get("levels", {}).values():
    for m in level.get("models", []):
        mn = m.get("model_name", "")
        if "/" in mn:
            owner, model = mn.split("/", 1)
            fuel_map[model] = f"https://fuel.gazebosim.org/1.0/{owner}/models/{model}"

text = world_path.read_text(encoding="utf-8")
replaced = []
for model_name, fuel_uri in fuel_map.items():
    local_uri = f"model://{model_name}"
    if local_uri in text:
        text = text.replace(local_uri, fuel_uri)
        replaced.append(model_name)

# The upstream Extinguisher DAE refers to a bare `Extinguisher.png`, which
# Gazebo GUI cannot resolve through the remote Fuel mesh URL. Use the local
# packaged copy where the texture sits beside the DAE.
text = text.replace(
    "https://fuel.gazebosim.org/1.0/OpenRobotics/models/Extinguisher",
    "model://hospital_extinguisher",
)

world_path.write_text(text, encoding="utf-8")
if replaced:
    print(f"Replaced {len(replaced)} model URI(s): {', '.join(replaced)}")
else:
    print("No model:// URIs to replace")

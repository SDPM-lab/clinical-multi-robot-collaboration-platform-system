// Builds Draco-compressed runtime copies of the source GLBs and refreshes
// src/config/compressedModels.js. Source GLBs in public/models/ stay untouched because
// tests and the Blender/route scripts read their raw geometry.
//
// Usage: npm run models:compress   (downloads @gltf-transform/cli through npx on first run)
import { createHash } from 'node:crypto'
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const frontendRoot = fileURLToPath(new URL('..', import.meta.url))
const modelsDir = path.join(frontendRoot, 'public/models')
const outputDir = path.join(modelsDir, 'draco')
const decoderDir = path.join(frontendRoot, 'public/draco')
const manifestPath = path.join(frontendRoot, 'src/config/compressedModels.js')
const models = ['AGIBOT_A2D.glb', 'baymax_nurse.glb', 'L1__flat.glb', 'hospital_L1_environment.glb', 'hospital_overview.glb', 'robot.glb']

const hash = file => createHash('sha256').update(readFileSync(file)).digest('hex').slice(0, 12)

mkdirSync(outputDir, { recursive: true })
mkdirSync(decoderDir, { recursive: true })
const decoderSource = path.join(frontendRoot, 'node_modules/three/examples/jsm/libs/draco/gltf')
for (const file of ['draco_decoder.js', 'draco_decoder.wasm', 'draco_wasm_wrapper.js'])
  copyFileSync(path.join(decoderSource, file), path.join(decoderDir, file))

const entries = []
for (const name of models) {
  const source = path.join(modelsDir, name)
  const output = path.join(outputDir, name)
  const result = spawnSync('npx', ['--yes', '@gltf-transform/cli@4', 'draco', source, output], { stdio: 'inherit' })
  if (result.status !== 0) throw new Error(`Compressing ${name} failed`)
  entries.push(`  '${name}': Object.freeze({ source: '${hash(source)}', version: '${hash(output)}' }),`)
}

writeFileSync(manifestPath, `// Generated by \`npm run models:compress\` — do not edit by hand.
// Draco-compressed runtime copies of the source GLBs in public/models/.
// \`source\` is the sha256 prefix of the source GLB the copy was built from; the
// compressedModels test fails when a source GLB changes without recompressing.
export const COMPRESSED_MODELS = Object.freeze({
${entries.join('\n')}
})
`)
console.log(`Updated ${path.relative(frontendRoot, manifestPath)}`)

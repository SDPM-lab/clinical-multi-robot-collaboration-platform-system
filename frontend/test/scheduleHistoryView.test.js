import { mount,flushPromises } from '@vue/test-utils'
import { computed } from 'vue'
import { describe,it,expect,vi,beforeEach,afterEach } from 'vitest'
import ScheduleHistoryView from '@/views/ScheduleHistoryView.vue'
import HistorySummary from '@/components/history/HistorySummary.vue'
import HospitalMiniMap from '@/components/dispatch/HospitalMiniMap.vue'
import { setLocale } from '@/i18n/index.js'
import { addDays, dayKey } from '@/data/scheduleHistory.js'

const historyControl=vi.hoisted(()=>({events:[]}))
vi.mock('@/data/scheduleHistorySource.js',()=>({createHistorySource:()=>computed(()=>({events:historyControl.events,demo:false,error:''}))}))

const makeHistoryEvents=()=>{
 const today=dayKey(new Date()),yesterday=addDays(today,-1)
 const make=(id,date,start,end,status,priority,routeCoordinates)=>({id,taskId:`H${id}`,title:'藥品配送',robotId:'R01',robotName:'Robot 01',start:`${date}T${start}`,end:`${date}T${end}`,startLocation:'Pharmacy',endLocation:'Nurse Reception',status,priority,routeCoordinates,requiredCapabilities:['Navigation','MedicineDelivery'],note:'Keep refrigerated',createdAt:`${date}T07:00:00`})
 return [
  make('001',today,'10:00:00','10:35:00','completed','high',[[180,330],[530,270]]),
  make('002',today,'09:00:00','09:35:00','cancelled','normal',[[250,270],[570,440]]),
  make('003',today,'08:00:00','08:35:00','failed','urgent',[[450,230],[690,365]]),
  make('004',today,'00:00:00','00:01:00','running','low',[[530,270],[180,330]]),
  make('005',yesterday,'11:00:00','11:35:00','completed','high',[[570,440],[250,270]]),
 ]
}

beforeEach(()=>{historyControl.events=makeHistoryEvents();vi.stubGlobal('ResizeObserver',class{observe(){} disconnect(){}})})
afterEach(()=>{setLocale('zh-TW');vi.unstubAllGlobals()})
const ready=async()=>{const wrapper=mount(ScheduleHistoryView);await vi.dynamicImportSettled();await flushPromises();return wrapper}

describe('schedule history dashboard',()=>{
 it('shows a compact status strip, task list, route and history details',async()=>{
  const wrapper=await ready()
  const cards=wrapper.findAll('.history-metric')
  expect(cards).toHaveLength(4)
  expect(cards.map(card=>card.find('.metric-label').text())).toEqual(['任務總數','已完成','已取消','失敗'])
  expect(cards.map(card=>card.attributes('data-status'))).toEqual(['all','completed','cancelled','failed'])
  expect(cards.every(card=>card.find('.metric-icon').exists())).toBe(true)
  expect(cards.every(card=>card.get('.history-metric-reading').findAll(':scope > *').length===2)).toBe(true)
  expect(cards.every(card=>card.find('.metric-sparkline .spark-line').exists())).toBe(true)
  expect(cards.some(card=>card.attributes('data-status')==='running')).toBe(false)
  expect(wrapper.find('.status-switch').exists()).toBe(false)
  expect(wrapper.text()).not.toContain('HISTORY / OPERATIONS')
  expect(wrapper.text()).not.toContain('時間模式')
  expect(wrapper.get('.list-header').element.firstElementChild.classList.contains('history-search')).toBe(true)
  expect(wrapper.find('.heading-copy').exists()).toBe(false)
  expect(wrapper.get('.history-column-head').findAll('span').map(item=>item.text())).toEqual(['任務類型','時間','機器人','起點 → 終點','優先級','狀態','任務時長'])
  expect(wrapper.get('.history-column-head').element.nextElementSibling.classList.contains('history-list-scroll')).toBe(true)
  expect(wrapper.get('.history-list-scroll').find('.history-column-head').exists()).toBe(false)
  expect(wrapper.find('.history-calendar').exists()).toBe(false)
  expect(wrapper.find('.history-date-picker input').exists()).toBe(false)
  expect(wrapper.get('.history-date-picker').findAll('svg')).toHaveLength(1)
  expect(Array.from(wrapper.get('.date-navigation').element.children).map(child=>child.tagName)).toEqual(['BUTTON','DIV','BUTTON'])
  expect(wrapper.get('.history-row').get('.row-task-id').text()).toMatch(/^H\d+/)
  expect(wrapper.get('.history-row').get('.row-identity').findAll(':scope > *')).toHaveLength(2)
  expect(wrapper.get('.history-row').get('.row-time').text()).toContain('–')
  expect(wrapper.get('.history-row').get('.duration-value').text()).toMatch(/^\d+$/)
  expect(wrapper.get('.history-row').get('.duration-unit').text()).toBe('分鐘')
  expect(wrapper.findAll('.status-label').every(label=>!label.find('svg').exists())).toBe(true)
  expect(wrapper.find('.row-identity i').exists()).toBe(false)
  expect(wrapper.find('.row-arrow').exists()).toBe(false)
  expect(wrapper.find('.list-toolbar').exists()).toBe(false)
  expect(wrapper.get('.list-header').find('.history-search').exists()).toBe(true)
  expect(wrapper.get('.list-header').find('.filter-root').exists()).toBe(true)
  expect(wrapper.get('.list-header').find('.range-controls').exists()).toBe(true)
  expect(wrapper.get('.list-header').find('.view-switch').exists()).toBe(true)
  expect(wrapper.findAll('.history-row').length).toBeGreaterThan(1)
  expect(wrapper.get('.history-detail').text()).toContain('任務路線')
  expect(wrapper.get('.history-detail').text()).toContain('任務歷程')
  expect(wrapper.get('.task-record').text()).toContain('Keep refrigerated')
  expect(wrapper.get('.task-record').text()).toContain('導航')
  expect(wrapper.get('.task-record').text()).toContain('藥品配送')
  expect(wrapper.get('.task-record').text()).toContain('建立時間')
  expect(wrapper.find('.task-record h3').exists()).toBe(false)
  expect(wrapper.get('.history-side-column').element.firstElementChild.classList.contains('task-record-panel')).toBe(true)
  expect(wrapper.get('.task-record-panel h2').text()).toContain(wrapper.get('.detail-header h2 span').text())
  expect(wrapper.find('.detail-header button').exists()).toBe(false)
  expect(wrapper.find('.detail-task-title').exists()).toBe(false)
  expect(wrapper.findComponent(HospitalMiniMap).props()).toMatchObject({historical:true,readOnly:true,routeProgress:1})
  expect(wrapper.find('.mini-grid').exists()).toBe(false)
  wrapper.unmount()
 })
 it('uses summary cards as status filters and preserves search and advanced filters',async()=>{
  const wrapper=await ready()
  const cards=wrapper.findAll('.history-metric')
  await cards[1].trigger('click')
  expect(cards[1].attributes('aria-pressed')).toBe('true')
  expect(wrapper.findAll('.history-row').every(row=>row.find('[data-status=completed]').exists())).toBe(true)
  await cards[2].trigger('click')
  expect(wrapper.findAll('.history-row').every(row=>row.find('[data-status=cancelled]').exists())).toBe(true)
  await cards[3].trigger('click')
  expect(wrapper.findAll('.history-row').length).toBeGreaterThan(0)
  expect(wrapper.findAll('.history-row').every(row=>row.find('[data-status=failed]').exists())).toBe(true)
  await cards[0].trigger('click')
  expect(wrapper.findAll('.history-row').length).toBeGreaterThan(3)
  await wrapper.get('.icon-control').trigger('click')
  await wrapper.findAll('.filter-choice button').find(button=>button.text()==='高').trigger('click')
  expect(wrapper.get('.icon-control').text()).toContain('1')
  await wrapper.get('.history-search input').setValue('impossible-task-id')
  expect(wrapper.find('.history-empty').exists()).toBe(true)
  wrapper.unmount()
 })
 it('navigates dates from the toolbar and keeps the selected task detail in sync',async()=>{
  const wrapper=await ready()
  const picker=wrapper.get('.history-date-picker')
  const original=picker.text()
  await wrapper.get('.range-controls').findAll(':scope > button')[0].trigger('click')
  expect(picker.text()).not.toBe(original)
  await wrapper.get('.range-controls').findAll(':scope > button')[1].trigger('click')
  expect(picker.text()).toBe(original)
  const firstRow=wrapper.get('.history-row')
  expect(wrapper.get('.detail-header').text()).toContain(firstRow.get('.row-task-id').text())
  const originalRoute=wrapper.findComponent(HospitalMiniMap).props('routeCoordinates')
  await wrapper.findAll('.history-row')[1].trigger('click')
  expect(wrapper.findComponent(HospitalMiniMap).props('routeCoordinates')).not.toEqual(originalRoute)
  expect(wrapper.get('.task-record-panel h2').text()).toContain(wrapper.findAll('.history-row')[1].get('.row-task-id').text())
  wrapper.unmount()
 })
 it('uses the selected date as the anchor for daily, weekly, and monthly lists',async()=>{
  const wrapper=await ready()
  const picker=wrapper.get('.history-date-picker')
  const anchor=addDays(dayKey(new Date()),-1)
  await picker.trigger('click')
  expect(picker.attributes('aria-expanded')).toBe('true')
  expect(wrapper.findAll('.calendar-day')).toHaveLength(42)
  await wrapper.get(`.calendar-day[data-date="${anchor}"]`).trigger('click')
  expect(picker.text()).toBe(anchor.replaceAll('-', '/'))
  expect(picker.attributes('aria-expanded')).toBe('false')
  const modes=wrapper.findAll('.view-switch button')
  await modes[0].trigger('click')
  expect(modes[0].attributes('aria-pressed')).toBe('true')
  expect(wrapper.findAll('.date-group')).toHaveLength(1)
  const dailyCount=wrapper.findAll('.history-row').length
  await modes[1].trigger('click')
  expect(modes[1].attributes('aria-pressed')).toBe('true')
  expect(wrapper.findAll('.history-row').length).toBeGreaterThanOrEqual(dailyCount)
  await modes[2].trigger('click')
  expect(modes[2].attributes('aria-pressed')).toBe('true')
  expect(wrapper.findAll('.history-row').length).toBeGreaterThanOrEqual(dailyCount)
  wrapper.unmount()
 })
 it('changes months in the styled calendar and returns to today',async()=>{
  const wrapper=await ready()
  const picker=wrapper.get('.history-date-picker')
  await picker.trigger('click')
  const originalMonth=wrapper.get('.calendar-header strong').text()
  await wrapper.get('.calendar-header button').trigger('click')
  expect(wrapper.get('.calendar-header strong').text()).not.toBe(originalMonth)
  await wrapper.get('.calendar-popover footer button').trigger('click')
  expect(picker.text()).toBe(dayKey(new Date()).replaceAll('-', '/'))
  expect(wrapper.find('.calendar-popover').exists()).toBe(false)
  wrapper.unmount()
 })
 it('switches every visible history label to English and persists the selection',async()=>{
  const wrapper=await ready()
  setLocale('en')
  await wrapper.vm.$nextTick()
  expect(wrapper.get('.schedule-history-page').attributes('aria-label')).toBe('Schedule History')
  expect(wrapper.get('.history-search input').attributes('placeholder')).toBe('Search tasks, robots or locations')
  expect(wrapper.findAll('.metric-label').map(item=>item.text())).toEqual(['Total tasks','Completed','Cancelled','Failed'])
  expect(wrapper.findAll('.view-switch button').map(item=>item.text())).toEqual(['Daily','Weekly','Monthly'])
  expect(wrapper.get('.history-row').get('.row-time').text()).toContain('–')
  expect(wrapper.get('.history-detail').text()).toContain('Task timeline')
  expect(localStorage.getItem('hospital-rmf-locale')).toBe('en')
  wrapper.unmount()
 })
})


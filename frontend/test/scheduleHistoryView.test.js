import { mount,flushPromises } from '@vue/test-utils'
import { describe,it,expect,vi,afterEach } from 'vitest'
import ScheduleHistoryView from '@/views/ScheduleHistoryView.vue'
import HistorySummary from '@/components/history/HistorySummary.vue'
import HospitalMiniMap from '@/components/dispatch/HospitalMiniMap.vue'
import { setLocale } from '@/i18n/index.js'

afterEach(()=>setLocale('zh-TW'))
const ready=async()=>{const wrapper=mount(ScheduleHistoryView);await vi.dynamicImportSettled();await flushPromises();return wrapper}

describe('schedule history dashboard',()=>{
 it('shows the five requested filter cards, split time columns, route and history details',async()=>{
  const wrapper=await ready()
  const cards=wrapper.findAll('.history-metric')
  expect(cards).toHaveLength(5)
  expect(cards.map(card=>card.find('.metric-label').text())).toEqual(['任務總數','已完成','已取消','已超時','失敗／異常'])
  expect(cards.map(card=>card.attributes('data-status'))).toEqual(['all','completed','cancelled','overdue','failed'])
  expect(cards.every(card=>card.find('.metric-icon').exists())).toBe(true)
  expect(cards.every(card=>card.find('.metric-sparkline .spark-line').exists())).toBe(true)
  expect(cards.some(card=>card.find('.metric-label').text()==='執行中')).toBe(false)
  expect(wrapper.find('.status-switch').exists()).toBe(false)
  expect(wrapper.text()).not.toContain('HISTORY / OPERATIONS')
  expect(wrapper.text()).not.toContain('時間模式')
  expect(wrapper.get('.heading-copy').findAll(':scope > *').map(item=>item.text())).toEqual(['排程歷史',`${wrapper.findAll('.history-row').length} 筆任務`])
  expect(wrapper.get('.history-column-head').findAll('span').map(item=>item.text())).toEqual(['任務名稱','任務編號','開始時間','結束時間','機器人','起點 → 終點','優先級','狀態','任務時長'])
  expect(wrapper.get('.history-row').get('.row-task-id').text()).toMatch(/^H\d+/)
  expect(wrapper.get('.history-row').get('.duration-value').text()).toMatch(/^\d+$/)
  expect(wrapper.get('.history-row').get('.duration-unit').text()).toBe('分鐘')
  expect(wrapper.findAll('.status-label').every(label=>!label.find('svg').exists())).toBe(true)
  expect(wrapper.find('.row-identity i').exists()).toBe(false)
  expect(wrapper.find('.row-arrow').exists()).toBe(false)
  expect(wrapper.find('.list-toolbar').exists()).toBe(false)
  expect(wrapper.get('.list-header').find('.history-search').exists()).toBe(true)
  expect(wrapper.get('.list-header').find('.filter-root').exists()).toBe(true)
  expect(wrapper.get('.list-header').find('.range-controls').exists()).toBe(true)
  expect(wrapper.get('.list-header').find('.view-switch').exists()).toBe(true)
  expect(wrapper.findAll('.history-row').length).toBeGreaterThan(1)
  expect(wrapper.get('.history-detail').text()).toContain('任務路線')
  expect(wrapper.get('.history-detail').text()).toContain('任務歷程')
  expect(wrapper.find('.detail-facts').exists()).toBe(false)
  expect(wrapper.find('.detail-task-title').exists()).toBe(false)
  expect(wrapper.findComponent(HospitalMiniMap).props()).toMatchObject({historical:true,readOnly:true,routeProgress:1})
  expect(wrapper.find('.calendar-navigation').exists()).toBe(false)
  expect(wrapper.get('.calendar-header').findAll('button')).toHaveLength(2)
  expect(wrapper.find('.mini-grid i').exists()).toBe(false)
  expect(wrapper.findAll('.mini-grid > span').map(day=>day.text())).toEqual(['一','二','三','四','五','六','日'])
  expect(wrapper.findAll('.mini-grid button').some(button=>button.classes().some(name=>name.startsWith('intensity-')&&name!=='intensity-none'))).toBe(true)
  wrapper.unmount()
 })
 it('uses summary cards as status filters and preserves search and advanced filters',async()=>{
  const wrapper=await ready()
  const cards=wrapper.findAll('.history-metric')
  await cards[1].trigger('click')
  expect(cards[1].attributes('aria-pressed')).toBe('true')
  expect(wrapper.findAll('.history-row').every(row=>row.find('[data-status=completed]').exists())).toBe(true)
  await cards[2].trigger('click')
  expect(wrapper.findAll('.history-row').every(row=>row.find('[data-status=cancelled]').exists())).toBe(true)
  await cards[3].trigger('click')
  expect(wrapper.findAll('.history-row').length).toBeGreaterThan(0)
  expect(wrapper.findAll('.history-row').every(row=>row.find('[data-status=overdue]').exists())).toBe(true)
  await cards[0].trigger('click')
  expect(wrapper.findAll('.history-row').length).toBeGreaterThan(3)
  await wrapper.get('.icon-control').trigger('click')
  await wrapper.findAll('.filter-choice button').find(button=>button.text()==='高').trigger('click')
  expect(wrapper.get('.icon-control').text()).toContain('1')
  await wrapper.get('.history-search input').setValue('impossible-task-id')
  expect(wrapper.find('.history-empty').exists()).toBe(true)
  wrapper.unmount()
 })
 it('selects a continuous week in the calendar and synchronizes the chosen task details',async()=>{
  const wrapper=await ready()
  const initialMonth=wrapper.get('.calendar-header h2').text()
  await wrapper.get('.calendar-header').findAll('button')[1].trigger('click')
  expect(wrapper.get('.calendar-header h2').text()).not.toBe(initialMonth)
  expect(wrapper.findAll('.mini-grid button')).toHaveLength(42)
  await wrapper.get('.calendar-header').findAll('button')[0].trigger('click')
  expect(wrapper.get('.calendar-header h2').text()).toBe(initialMonth)
  expect(wrapper.findAll('.mini-grid .is-in-week')).toHaveLength(7)
  expect(wrapper.findAll('.mini-grid .is-week-start')).toHaveLength(1)
  expect(wrapper.findAll('.mini-grid .is-week-end')).toHaveLength(1)
  expect(wrapper.findAll('.mini-grid button:not(.is-in-week)').every(button=>button.classes().includes('calendar-default')&&button.classes().includes('intensity-none'))).toBe(true)
  const taskDay=wrapper.findAll('.mini-grid button').find(button=>button.classes().some(name=>name.startsWith('intensity-')&&name!=='intensity-none')&&!button.classes().includes('is-anchor'))
  await taskDay.trigger('click')
  expect(wrapper.findAll('.view-switch button')[1].attributes('aria-pressed')).toBe('true')
  expect(wrapper.findAll('.mini-grid .is-in-week')).toHaveLength(7)
  const firstRow=wrapper.get('.history-row')
  expect(wrapper.get('.detail-header').text()).toContain(firstRow.get('.row-task-id').text())
  const originalRoute=wrapper.findComponent(HospitalMiniMap).props('routeCoordinates')
  const anotherRow=wrapper.findAll('.history-row')[1]
  await anotherRow.trigger('click')
  expect(wrapper.findComponent(HospitalMiniMap).props('routeCoordinates')).not.toEqual(originalRoute)
  wrapper.unmount()
 })
 it('uses the clicked calendar day as the anchor for daily, weekly, and monthly lists',async()=>{
  const wrapper=await ready()
  const target=wrapper.find('[data-date="2026-09-15"]')
  await target.trigger('click')
  expect(target.attributes('aria-pressed')).toBe('true')

  const modes=wrapper.findAll('.view-switch button')
  await modes[0].trigger('click')
  expect(modes[0].attributes('aria-pressed')).toBe('true')
  expect(wrapper.findAll('.mini-grid button:not(.calendar-selected)').every(button=>button.classes().includes('calendar-default')&&button.classes().includes('intensity-none'))).toBe(true)
  expect(wrapper.findAll('.date-group')).toHaveLength(1)
  expect(wrapper.get('.date-group h2').text()).toContain('9月15日')
  const dailyCount=wrapper.findAll('.history-row').length

  await modes[1].trigger('click')
  expect(modes[1].attributes('aria-pressed')).toBe('true')
  expect(wrapper.findAll('.mini-grid .is-in-week')).toHaveLength(7)
  expect(wrapper.findAll('.history-row').length).toBeGreaterThan(dailyCount)

  await modes[2].trigger('click')
  expect(modes[2].attributes('aria-pressed')).toBe('true')
  expect(wrapper.findAll('.date-group').every(group=>group.get('h2').text().includes('2026年9月'))).toBe(true)
  wrapper.unmount()
 })
 it('switches every visible history label to English and persists the selection',async()=>{
  const wrapper=await ready()
  setLocale('en')
  await wrapper.vm.$nextTick()
  expect(wrapper.get('.heading-copy h1').text()).toBe('Schedule History')
  expect(wrapper.findAll('.metric-label').map(item=>item.text())).toEqual(['Total tasks','Completed','Cancelled','Overdue','Failed / Alert'])
  expect(wrapper.findAll('.view-switch button').map(item=>item.text())).toEqual(['Daily','Weekly','Monthly'])
  expect(wrapper.get('.history-column-head').text()).toContain('Start time')
  expect(wrapper.get('.history-detail').text()).toContain('Task timeline')
  expect(localStorage.getItem('hospital-rmf-locale')).toBe('en')
  wrapper.unmount()
 })
})

it('uses arrow direction and color that consistently follow the signed trend',()=>{
 const record=status=>({status,start:'2026-09-16T09:00:00',end:'2026-09-16T09:30:00'})
 const wrapper=mount(HistorySummary,{props:{period:'weekly',events:[record('completed'),record('completed')],previousEvents:[record('completed'),record('cancelled'),record('failed')]}})
 const cards=wrapper.findAll('.history-metric')
 expect(cards.map(card=>card.find('.metric-trend').attributes('data-tone'))).toEqual(['bad','good','bad','flat','bad'])
 expect(cards[0].find('.lucide-arrow-down').exists()).toBe(true)
 expect(cards[1].find('.lucide-arrow-up').exists()).toBe(true)
 expect(cards[2].find('.lucide-arrow-down').exists()).toBe(true)
 expect(cards[2].find('.metric-trend').text()).toContain('-1')
 expect(cards[4].find('.metric-trend').text()).toContain('-1')
 wrapper.unmount()
})

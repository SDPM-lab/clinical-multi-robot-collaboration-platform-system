import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import TaskDispatchView from '@/views/TaskDispatchView.vue'
import TaskForm from '@/components/dispatch/TaskForm.vue'
import DispatchMapScene from '@/components/dispatch/DispatchMapScene.vue'
import TaskScheduleSidebar from '@/components/dispatch/TaskScheduleSidebar.vue'
import { taskApi } from '@/services/taskApi.js'
import { demoFleetStore } from '@/stores/demoFleetStore.js'
import { setLocale } from '@/i18n/index.js'
const graph=JSON.parse(readFileSync(resolve('public/generated/rmf-navigation.json'),'utf8'))
const floorplan=JSON.parse(readFileSync(resolve('public/generated/hospital-floorplan.json'),'utf8'))
let wrapper
beforeEach(()=>{
  vi.spyOn(taskApi,'getTasks').mockResolvedValue(demoFleetStore.tasks.value.map(task=>({...task,date:task.date || '2026-08-31'})))
  vi.spyOn(taskApi,'getRobots').mockResolvedValue([...demoFleetStore.robots.value])
  vi.useFakeTimers({toFake:['Date']})
  vi.setSystemTime(new Date(2026,7,31,9,30))
  vi.stubGlobal('ResizeObserver',class{observe(){} disconnect(){}})
  vi.stubGlobal('fetch',vi.fn(async url=>({ok:true,json:async()=>String(url).includes('hospital-floorplan')?floorplan:graph})))
})
afterEach(()=>{vi.useRealTimers();wrapper?.unmount();setLocale('zh-TW');vi.restoreAllMocks();vi.unstubAllGlobals()})
describe('task dispatch workspace',()=>{
  it('defaults to automatic selection with optional notes and marks required fields',async()=>{
    wrapper=mount(TaskForm,{props:{robots:demoFleetStore.robots.value,locations:['Pharmacy','Nurse Reception'],origin:'Pharmacy',destination:'Nurse Reception',date:'2026-08-31'}})
    expect(wrapper.get('.robot-trigger').text()).toContain('Default')
    expect(wrapper.find('.robot-trigger-battery').exists()).toBe(false)
    expect(wrapper.findAll('.required-marker')).toHaveLength(6)
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('submit')[0][0]).toEqual(expect.objectContaining({robotId:null,note:null,scheduledAt:new Date('2026-08-31T09:30:00').toISOString()}))
    await wrapper.get('.robot-trigger').trigger('click')
    await wrapper.findAll('.robot-options [role="option"]')[1].trigger('click')
    await wrapper.get('.robot-trigger').trigger('click')
    await wrapper.findAll('.robot-options [role="option"]')[0].trigger('click')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('submit')[1][0].robotId).toBeNull()
  })
  it('chooses a schedule time from the custom picker and saves it',async()=>{
    wrapper=mount(TaskScheduleSidebar,{props:{date:'2026-08-31',robots:[],editing:true,tasks:[{id:'A',startTime:'09:30:00',endTime:'09:42:00',title:'藥品配送',origin:'Pharmacy',destination:'Nurse Reception',priority:'normal'}]}})
    await wrapper.get('.schedule-time-toggle').trigger('click')
    expect(wrapper.findAll('.schedule-time-column')[0].findAll('[role="option"]')).toHaveLength(24)
    expect(wrapper.findAll('.schedule-time-column')[1].findAll('[role="option"]')).toHaveLength(60)
    await wrapper.findAll('.schedule-time-column')[0].findAll('button')[0].trigger('click')
    await wrapper.findAll('.schedule-time-column')[1].findAll('button')[11].trigger('click')
    expect(wrapper.get('.schedule-time-entry input').element.value).toBe('00:11')
    await wrapper.get('.schedule-inline-edit > button').trigger('click')
    expect(wrapper.emitted('reschedule')[0]).toEqual(['A','00:11'])
    await wrapper.get('.schedule-time-entry input').setValue('25:99')
    expect(wrapper.get('.schedule-inline-edit > button').attributes('disabled')).toBeDefined()
  })
  it('uses the current local date and time and refreshes them on reset',async()=>{
    vi.setSystemTime(new Date(2026,9,25,14,11))
    wrapper=mount(TaskDispatchView,{global:{stubs:{DispatchMapScene:true}}})
    const form=wrapper.getComponent(TaskForm)
    expect(form.get('.date-trigger').text()).toContain('2026 / 10 / 25')
    expect(form.get('#dispatch-start-time').element.value).toBe('02:11 PM')
    vi.setSystemTime(new Date(2026,9,26,0,5))
    await form.get('footer button[type="button"]').trigger('click')
    expect(form.get('.date-trigger').text()).toContain('2026 / 10 / 26')
    expect(form.get('#dispatch-start-time').element.value).toBe('12:05 AM')
  })
  it('uses a themed calendar and independent hour and minute columns in creation',async()=>{
    wrapper=mount(TaskForm,{props:{robots:[],locations:['Pharmacy'],date:'2026-08-31',origin:'Pharmacy',destination:'Pharmacy'}})
    expect(wrapper.find('input[type="date"]').exists()).toBe(false)
    await wrapper.get('.date-trigger').trigger('click')
    await wrapper.get('[data-date="2026-09-01"]').trigger('click')
    expect(wrapper.get('.date-trigger').text()).toContain('2026 / 09 / 01')
    expect(wrapper.find('.dispatch-calendar').exists()).toBe(false)
    await wrapper.get('.dispatch-time-entry button').trigger('click')
    const columns=wrapper.findAll('.time-scroll-column')
    expect(columns[0].findAll('button')).toHaveLength(24)
    expect(columns[1].findAll('button')).toHaveLength(60)
    await columns[0].findAll('button')[0].trigger('click')
    await columns[1].findAll('button')[11].trigger('click')
    expect(wrapper.get('#dispatch-start-time').element.value).toBe('12:11 AM')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('submit')[0][0]).toEqual(expect.objectContaining({date:'2026-09-01',startTime:'00:11:00'}))
  })
  it('shows the task code in notifications and cards while deleting by internal ID',async()=>{
    taskApi.getTasks.mockResolvedValue([{id:'internal-id',taskCode:'T0042',title:'藥品配送',date:'2026-08-31',startTime:'09:30:00',endTime:'09:30:00',origin:'Pharmacy',destination:'Nurse Reception',priority:'normal'}])
    vi.spyOn(taskApi,'createTask').mockResolvedValue({id:'internal-id',taskCode:'T0042'})
    const remove=vi.spyOn(taskApi,'deleteTask').mockResolvedValue(null)
    wrapper=mount(TaskDispatchView,{global:{stubs:{DispatchMapScene:true}}})
    await flushPromises()
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(wrapper.get('.dispatch-toast').text()).toContain('T0042')
    expect(wrapper.get('.dispatch-toast').text()).not.toContain('internal-id')
    expect(wrapper.get('.schedule-card-top').text()).toContain('T0042')
    await wrapper.get('.schedule-edit').trigger('click')
    await wrapper.get('.schedule-delete').trigger('click')
    expect(wrapper.get('[role="alertdialog"]').text()).toContain('T0042')
    await wrapper.get('.dispatch-confirm-actions .is-danger').trigger('click')
    await flushPromises()
    expect(remove).toHaveBeenCalledWith('internal-id')
    expect(wrapper.get('.dispatch-toast').text()).toContain('T0042')
  })
  it('shows creation by default and switches the shared left panel to schedule',async()=>{
    wrapper=mount(TaskDispatchView, { global: { stubs: { DispatchMapScene: true } } });await flushPromises()
    expect(wrapper.get('#dispatch-create-tab').attributes('aria-selected')).toBe('true')
    expect(wrapper.get('#dispatch-schedule-panel').attributes('style')).toContain('display: none')
    await wrapper.get('#dispatch-schedule-tab').trigger('click')
    expect(wrapper.get('#dispatch-schedule-tab').attributes('aria-selected')).toBe('true')
    expect(wrapper.get('#dispatch-create-panel').attributes('style')).toContain('display: none')
    expect(wrapper.get('.schedule-sidebar').text()).toContain('藥品配送')
    wrapper.getComponent(DispatchMapScene).vm.$emit('select-location','Laboratory');await flushPromises()
    expect(wrapper.get('#dispatch-create-tab').attributes('aria-selected')).toBe('true')
    expect(wrapper.getComponent(TaskForm).props('origin')).toBe('Laboratory')
  })
  it('shows concurrent robots as separate compact schedule entries',()=>{
    const schedule=mount(TaskScheduleSidebar,{props:{date:'2026-08-31',robots:[{id:'R01',name:'Robot 01'},{id:'R02',name:'Robot 02'},{id:'R03',name:'Robot 03'}],tasks:[
      {id:'A',robotId:'R01',startTime:'09:30:00',endTime:'09:42:00',title:'藥品配送',origin:'藥局',destination:'護理站',status:'executing'},
      {id:'B',robotId:'R02',startTime:'09:30:00',endTime:'09:50:00',title:'檢體運送',origin:'診間',destination:'檢驗室',status:'executing'},
      {id:'C',robotId:'R03',startTime:'09:30:00',endTime:'09:45:00',title:'物資配送',origin:'倉庫',destination:'病房',status:'executing'},
    ]}})
    expect(schedule.findAll('.schedule-item')).toHaveLength(3)
    expect(schedule.findAll('.schedule-slot')).toHaveLength(1)
    expect(schedule.find('.schedule-time strong').text()).toBe('09:30')
    expect(schedule.findAll('.schedule-card-top').map((card)=>card.text())).toEqual(['A · R01','B · R02','C · R03'])
    expect(schedule.find('.schedule-slot').classes()).toContain('is-concurrent')
    expect(schedule.findAll('.schedule-item').map((item)=>item.attributes('title'))).toEqual([
      'Robot 01 · 藥品配送 · 藥局 → 護理站 · 09:30–09:42',
      'Robot 02 · 檢體運送 · 診間 → 檢驗室 · 09:30–09:50',
      'Robot 03 · 物資配送 · 倉庫 → 病房 · 09:30–09:45',
    ])
    expect(schedule.find('.schedule-status').exists()).toBe(false)
    expect(schedule.find('.schedule-progress').exists()).toBe(false)
    schedule.unmount()
  })
  it('uses priority colors for task borders and creation choices',async()=>{
    const tasks=['low','normal','high','emergency'].map((priority,index)=>({id:`P${index}`,robotId:'R01',startTime:`${String(index+8).padStart(2,'0')}:30:00`,endTime:`${String(index+8).padStart(2,'0')}:42:00`,title:'藥品配送',origin:'藥局',destination:'護理站',priority}))
    const schedule=mount(TaskScheduleSidebar,{props:{date:'2026-08-31',robots:[{id:'R01',name:'Robot 01'}],tasks}})
    expect(schedule.findAll('.schedule-item').map(item=>item.element.style.getPropertyValue('--item-color'))).toEqual(['#E0BD45','#FB9966','#D65B57','#954D43'])
    schedule.unmount()
    wrapper=mount(TaskDispatchView,{global:{stubs:{DispatchMapScene:true}}});await flushPromises()
    const choices=wrapper.findAll('.priority-control button')
    expect(choices.map(item=>item.element.style.getPropertyValue('--priority-color'))).toEqual(['#E0BD45','#FB9966','#D65B57','#954D43'])
    expect(wrapper.find('.robot-summary').exists()).toBe(false)
    await wrapper.get('.robot-trigger').trigger('click')
    expect(wrapper.get('.task-panel').classes()).toContain('is-robot-picker-open')
    expect(wrapper.get('.create-button').exists()).toBe(true)
    await wrapper.get('.robot-trigger').trigger('click')
    expect(wrapper.get('.task-panel').classes()).not.toContain('is-robot-picker-open')
  })
  it('links form endpoints, map selection and robot status while retaining all payload fields',async()=>{
    wrapper=mount(TaskDispatchView, { global: { stubs: { DispatchMapScene: true } } });await flushPromises()
    const form=wrapper.getComponent(TaskForm),map=wrapper.getComponent(DispatchMapScene)
    expect(map.props('routeConfirmed')).toBe(false)
    map.vm.$emit('select-location', 'Laboratory'); await flushPromises()
    expect(form.props('origin')).toBe('Laboratory')
    expect(map.props('routeConfirmed')).toBe(false)
    map.vm.$emit('select-location', 'Ward A'); await flushPromises()
    expect(form.props('destination')).toBe('Ward A')
    expect(map.props('routeConfirmed')).toBe(true)
    map.vm.$emit('select-location', 'Pharmacy'); await flushPromises()
    expect(form.props('origin')).toBe('Pharmacy')
    expect(map.props('routeConfirmed')).toBe(false)
    await form.findAll('.location-trigger')[0].trigger('click')
    await form.findAll('.location-options [role="option"]')[6].trigger('click')
    expect(form.findAll('.location-trigger')[0].text()).toBe('檢驗室')
    expect(map.props('routeConfirmed')).toBe(false)
    await form.findAll('.location-trigger')[1].trigger('click')
    await form.findAll('.location-options [role="option"]')[7].trigger('click')
    expect(map.props('destination')).toBe('Pantry')
    expect(map.props('routeConfirmed')).toBe(true)
    expect(form.find('[aria-label="清除任務表單"]').exists()).toBe(false)
    expect(form.text()).not.toContain('預計結束時間')
    expect(form.text()).not.toContain('預估時長')
    expect(form.text()).not.toContain('示範模式')
    const note=form.get('textarea[placeholder="輸入交接方式或注意事項"]')
    await note.setValue('交給值班護理師')
    expect(form.find('input[required][type="text"]').exists()).toBe(true)
    expect(form.get('.required-capabilities').text()).toContain('導航')
    const create=vi.spyOn(taskApi,'createTask').mockResolvedValue({id:'server-task-1'})
    await form.get('form').trigger('submit')
    expect(create).toHaveBeenCalledWith(expect.objectContaining({origin:'Laboratory',destination:'Pantry',robotId:null,type:'藥品配送',taskType:'MedicineDelivery',title:'藥品配送',date:'2026-08-31',startTime:'09:30:00',durationSeconds:720,priority:'normal',note:'交給值班護理師'}))
    expect(form.props('locations')).not.toContain('Charging Station B')
  })
  it('edits directly in the schedule and asks before deleting',async()=>{
    wrapper=mount(TaskDispatchView, { global: { stubs: { DispatchMapScene: true } } });await flushPromises()
    expect(wrapper.get('.schedule-sidebar').text()).toContain('藥品配送')
    await wrapper.get('.schedule-date-navigation button[aria-label="後一天"]').trigger('click')
    expect(wrapper.get('.schedule-sidebar').text()).toContain('目前沒有排定任務')
    await wrapper.get('.schedule-date-navigation button[aria-label="前一天"]').trigger('click')
    await wrapper.get('.schedule-edit').trigger('click')
    expect(wrapper.get('.schedule-edit').attributes('aria-pressed')).toBe('true')
    expect(wrapper.find('.schedule-editor').exists()).toBe(false)
    expect(wrapper.findAll('.schedule-delete')).toHaveLength(5)
    const move=vi.spyOn(taskApi,'updateSchedule').mockResolvedValue(null)
    await wrapper.get('.schedule-inline-edit input').setValue('09:45')
    await wrapper.get('.schedule-inline-edit > button').trigger('click')
    expect(move).toHaveBeenCalledWith('T001',new Date('2026-08-31T09:45:00').toISOString())
    const remove=vi.spyOn(taskApi,'deleteTask').mockResolvedValue(null)
    await wrapper.get('.schedule-delete').trigger('click')
    expect(wrapper.get('[role="alertdialog"]').text()).toContain('T001')
    await wrapper.get('.dispatch-confirm-actions button').trigger('click')
    expect(remove).not.toHaveBeenCalled()
    await wrapper.get('.schedule-delete').trigger('click')
    await wrapper.get('.dispatch-confirm-actions .is-danger').trigger('click')
    await flushPromises()
    expect(remove).toHaveBeenCalledWith('T001')
    expect(wrapper.find('[role="alertdialog"]').exists()).toBe(false)
  })
  it('shows a localized delete confirmation and custom robot choices',async()=>{
    setLocale('en')
    wrapper=mount(TaskDispatchView, { global: { stubs: { DispatchMapScene: true } } });await flushPromises()
    const emergency=wrapper.get('.priority-control button[data-priority="emergency"]')
    expect(emergency.text()).toBe('Emergency')
    await emergency.trigger('click')
    expect(emergency.attributes('aria-pressed')).toBe('true')
    await wrapper.get('.robot-trigger').trigger('click')
    expect(wrapper.findAll('.robot-options [role="option"]')).toHaveLength(8)
    expect(wrapper.get('.robot-options').text()).toContain('Busy')
    await wrapper.findAll('.robot-options [role="option"]')[2].trigger('click')
    expect(wrapper.getComponent(TaskForm).props('robotId')).toBe('R02')
    await wrapper.get('.schedule-edit').trigger('click')
    await wrapper.get('.schedule-delete').trigger('click')
    expect(wrapper.get('[role="alertdialog"]').text()).toContain('Delete T001')
    expect(wrapper.get('.dispatch-confirm-actions .is-danger').text()).toBe('Delete')
  })
  it('uses styled task type choices and submits a stable AM/PM time',async()=>{
    wrapper=mount(TaskDispatchView, { global: { stubs: { DispatchMapScene: true } } });await flushPromises()
    const form=wrapper.getComponent(TaskForm)
    await form.get('.task-type-trigger').trigger('click')
    expect(form.findAll('.task-type-options [role="option"]')).toHaveLength(4)
    await form.findAll('.task-type-options [role="option"]')[1].trigger('click')
    expect(form.get('.task-type-trigger').text()).toBe('檢體配送')
    expect(form.get('.required-capabilities').text()).toContain('檢體配送')
    await form.get('#dispatch-start-time').setValue('02:45 PM')
    const create=vi.spyOn(taskApi,'createTask').mockResolvedValue({id:'server-task-1'})
    await form.get('form').trigger('submit')
    expect(create).toHaveBeenCalledWith(expect.objectContaining({type:'檢體配送',taskType:'SpecimenDelivery',startTime:'14:45:00',durationSeconds:720}))
  })
  it('returns the schedule to the current local date',async()=>{
    wrapper=mount(TaskDispatchView, { global: { stubs: { DispatchMapScene: true } } });await flushPromises()
    const now=new Date(), today=`${now.getFullYear()}-${String(now.getMonth()+1).padStart(2,'0')}-${String(now.getDate()).padStart(2,'0')}`
    await wrapper.get('.schedule-date-navigation button[aria-label="後一天"]').trigger('click')
    expect(wrapper.getComponent(TaskScheduleSidebar).props('date')).not.toBe(today)
    await wrapper.get('.schedule-list-tools .schedule-today').trigger('click')
    expect(wrapper.getComponent(TaskScheduleSidebar).props('date')).toBe(today)
  })
  it('updates the form and deletion dialog when the language changes without reloading',async()=>{
    wrapper=mount(TaskDispatchView, { global: { stubs: { DispatchMapScene: true } } });await flushPromises()
    await wrapper.get('.schedule-edit').trigger('click')
    await wrapper.get('.schedule-delete').trigger('click')
    expect(wrapper.get('[role="alertdialog"]').text()).toContain('刪除這項任務')
    setLocale('en');await flushPromises()
    expect(wrapper.get('.task-panel').text()).toContain('Create task')
    expect(wrapper.get('[role="alertdialog"]').text()).toContain('Delete this task?')
    expect(wrapper.get('[role="alertdialog"]').text()).toContain('Medication delivery')
  })
  it('displays task validation errors and keeps the form available',async()=>{
    wrapper=mount(TaskDispatchView, { global: { stubs: { DispatchMapScene: true } } });await flushPromises()
    vi.spyOn(taskApi,'createTask').mockRejectedValue(new Error('與既有任務時間重疊。'))
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(wrapper.get('.dispatch-toast').text()).toContain('時間重疊')
    expect(wrapper.get('.create-button').exists()).toBe(true)
  })
})
